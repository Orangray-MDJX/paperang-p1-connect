import 'dart:typed_data';

import 'package:flutter_test/flutter_test.dart';
import 'package:integration_test/integration_test.dart';

import 'package:paperang_p1/services/pdf_service.dart';

/// 真机验证 MediaStore 保存链路（通道修复后）：
/// 直接调用服务层，不经 UI。运行：
///   flutter test integration_test/save_check_test.dart -d <serial>
void main() {
  IntegrationTestWidgetsFlutterBinding.ensureInitialized();

  testWidgets('saveToDownloads writes a png into MediaStore', (tester) async {
    // 8x8 红色 PNG（最小合法图，避免渲染依赖）
    final png = Uint8List.fromList(const [
      0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D,
      0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x08, 0x00, 0x00, 0x00, 0x08,
      0x08, 0x02, 0x00, 0x00, 0x00, 0x4B, 0x6D, 0x29, 0xDC, 0x00, 0x00, 0x00,
      0x1D, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9C, 0x62, 0xFC, 0xCF, 0xC0, 0xF0,
      0x1F, 0x00, 0x06, 0x18, 0x03, 0xC4, 0x75, 0x31, 0x1B, 0x00, 0x00, 0x00,
      0x00, 0x49, 0x45, 0x4E, 0x44, 0xAE, 0x42, 0x60, 0x82,
    ]);
    final uri = await PdfService.saveToDownloads(png, 'save-check');
    expect(uri, isNotEmpty);
    // ignore: avoid_print
    print('SAVED_URI=$uri');
  });
}
